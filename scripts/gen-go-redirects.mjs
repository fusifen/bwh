#!/usr/bin/env node
/**
 * Append `/go/[plan]` redirect rules to the built `_redirects`.
 *
 * Why this exists
 * ---------------
 * Every CTA on the site points at `/go/[plan]`, a server route with
 * `prerender = false` that logs the click and 302s to the vendor. On
 * **Cloudflare Workers** that route executes, and nothing here is needed.
 *
 * On **Cloudflare Pages** — plain static hosting, no Functions — the route does
 * not exist, so every button returns 404. This script emits the same redirects
 * as static rules so Pages deployments work.
 *
 * Why it is safe on Workers too
 * -----------------------------
 * `_redirects` is a Pages feature. Under the Workers adapter the file is served
 * as a static asset and never consulted, so leaving these rules in the output
 * does not shadow the server route or its click logging. They are inert there.
 *
 * Costs one thing: a static redirect cannot record the click server-side, so
 * attribution depends on the vendor's own tracking instead of `console.log`.
 * Commission is unaffected — the `aff` and `pid` parameters are identical.
 *
 * The URLs are built with the real `lib/affiliate` module rather than
 * reimplemented here, so a Pages link can never drift from a Workers link.
 *
 * Usage
 * -----
 *   npm run build:pages     # build, then run this
 */

import fs from 'node:fs/promises';
import path from 'node:path';
import { withProject, ROOT, heading, ok, warn, fail, detail } from './lib/project.mjs';

const OUT = path.join(ROOT, 'dist', 'client', '_redirects');

await withProject(async ({ cms, affiliate }) => {
  heading('生成 /go/ 静态跳转规则（Cloudflare Pages）');

  if (affiliate.isPlaceholderAffId(cms.AFF.affId)) {
    fail(`affId 仍是占位值（${cms.AFF.affId}），跳转会带上无效推广标识`);
    detail('请在 src/content/affiliate.json 填入真实 affId 后重新构建');
    process.exitCode = 1;
    return;
  }

  const plans = cms.getPlans();
  if (plans.length === 0) {
    fail('没有读到任何套餐，无法生成跳转规则');
    process.exitCode = 1;
    return;
  }

  const lines = [];
  let directed = 0;
  let generic = 0;

  for (const plan of plans) {
    const url = affiliate.buildAffUrl(cms.AFF, plan.affiliate?.pid);
    if (affiliate.hasUsablePid(plan)) directed += 1;
    else generic += 1;

    // 302, not 301: a corrected pid must not be pinned by a cached redirect.
    lines.push(`/go/${plan.slug}  ${url}  302`);
  }

  const block = [
    '',
    '# /go/[plan] — affiliate click redirects.',
    '#',
    '# Generated by scripts/gen-go-redirects.mjs for Cloudflare Pages, where the',
    '# server route does not run. 302 so a corrected pid is never cached. Inert',
    '# under the Workers adapter, which serves this file as a static asset and',
    '# keeps using the server route (and its click logging) instead.',
    ...lines,
    '',
  ].join('\n');

  let existing = '';
  try {
    existing = await fs.readFile(OUT, 'utf8');
  } catch {
    // No _redirects in the output yet — start from nothing.
  }

  // Match rule lines only. A plain `includes('/go/')` trips over the comment in
  // public/_redirects that explains why no rule *should* match /go/* — which is
  // precisely the file this script amends.
  const hasRules = existing
    .split('\n')
    .some((line) => line.trim().startsWith('/go/'));

  if (hasRules) {
    warn('_redirects 已含 /go/ 规则，跳过（如需重建请先清空 dist）');
    return;
  }

  await fs.writeFile(OUT, existing.replace(/\s*$/, '\n') + block, 'utf8');

  ok(`写入 ${plans.length} 条规则到 dist/client/_redirects`);
  detail(`定向链接 ${directed} 条，通用落地页 ${generic} 条（该套餐未填有效 pid）`);
  detail(`affId ${cms.AFF.affId} 已包含在全部链接中`);
  if (generic > 0) {
    warn(`${generic} 个套餐没有有效 pid，会跳到通用页而非具体商品`);
  }
});
